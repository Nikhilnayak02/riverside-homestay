const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'copilot-instructions.md');
const ROOMS = 3; // update this constant to change the documented rooms count

function readIfExists(p) {
  try { return fs.readFileSync(p, 'utf8'); } catch (e) { return null; }
}

function listAssets() {
  const assetsDir = path.join(ROOT, 'assets');
  try {
    return fs.readdirSync(assetsDir).filter(f => !f.startsWith('.')).sort();
  } catch (e) { return [] }
}

const index = readIfExists(path.join(ROOT, 'index.html')) || '';
const css = readIfExists(path.join(ROOT, 'css', 'styles.css')) || '';
const js = readIfExists(path.join(ROOT, 'js', 'main.js')) || '';
const assets = listAssets();

const titleMatch = index.match(/<title>([^<]+)<\/title>/i);
const h1Match = index.match(/<h1[^>]*>([^<]+)<\/h1>/i);
const title = (titleMatch && titleMatch[1]) || (h1Match && h1Match[1]) || 'Riverside Homestay';

const md = [];
md.push('**Project Summary**');
md.push(`- **Name:** ${title}`);
md.push('- **Purpose:** A small static marketing site for a riverside homestay property.');
md.push('');
md.push('**Quick Overview**');
md.push('- **Entry file:** `index.html` — main content and page sections (hero, story, packages, gallery, contact).');
md.push('- **Styles:** `css/styles.css` + small rules.');
md.push('- **Scripts:** `js/main.js` — site interactions.');
md.push(`- **Assets:** ${assets.length} files under \'assets/\'`);
md.push('');
md.push('**Rooms**');
md.push(`- The property has **${ROOMS}** guest rooms.`);
md.push('');
md.push('**Auto-generated asset list**');
if (assets.length) {
  assets.forEach(a => md.push(`- ${a}`));
} else {
  md.push('- (no assets found)');
}
md.push('');
md.push('**Where to edit**');
md.push('- Content: `index.html`');
md.push('- Styles: `css/styles.css`');
md.push('- Behavior: `js/main.js`');
md.push('');
md.push('*This file is auto-generated by `tools/generate-copilot-instructions.js` on push.*');

fs.writeFileSync(OUT, md.join('\n'));
console.log('Wrote', OUT);
